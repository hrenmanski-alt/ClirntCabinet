"""Convert an animated GIF into Unicode Braille frames for the showcase page.

Uses only Pillow + numpy. No third-party code from GitHub is executed.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
COLS = 84


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="GIF → Unicode Braille frames")
    p.add_argument("--src", default=str(ROOT / "assets" / "neon_flow.gif"))
    p.add_argument("--out", default=str(ROOT / "deploy_space" / "ascii_frames.js"))
    p.add_argument("--sample", default=str(ROOT / "deploy_space" / "ascii_sample.txt"))
    p.add_argument("--cols", type=int, default=COLS)
    p.add_argument("--limit", type=int, default=48)
    p.add_argument("--gamma", type=float, default=0.65)
    return p.parse_args()

# Braille dot bitmask: rows 0..3, cols 0..1.
BITS = np.array([[1, 8], [2, 16], [4, 32], [64, 128]], dtype=np.uint16)
BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], dtype=np.uint8)


def frame_to_braille(im: Image.Image, cols: int = COLS, gamma: float = 0.65) -> str:
    w, h = im.size
    rows = max(1, round(cols * h / (2 * w)))
    gray = ImageOps.autocontrast(im.convert("L"), cutoff=1)
    small = gray.resize((cols * 2, rows * 4), Image.Resampling.LANCZOS)
    pix = np.asarray(small, dtype=np.float32) / 255.0
    pix = np.clip(pix, 0, 1) ** gamma
    # ordered dithering threshold
    threshold = (BAYER[np.arange(rows * 4) % 4, :][:, np.arange(cols * 2) % 4] + 0.5) / 16.0
    on = pix > threshold

    chars: list[str] = []
    for r in range(rows):
        line: list[str] = []
        for c in range(cols):
            block = on[r * 4 : r * 4 + 4, c * 2 : c * 2 + 2]
            code = int(np.sum(block * BITS)) if block.shape == (4, 2) else 0
            line.append(chr(0x2800 + code))
        chars.append("".join(line))
    return "\n".join(chars)


def main() -> None:
    args = parse_args()
    src, out_js, out_txt = Path(args.src), Path(args.out), Path(args.sample)
    im = Image.open(src)
    total = im.n_frames
    indices = list(range(total))[: args.limit]

    frames: list[str] = []
    for i in indices:
        im.seek(i)
        frames.append(frame_to_braille(im, args.cols, args.gamma))

    out_js.write_text(
        f"// Generated by tools/gif_to_braille.py from {src.name}\n"
        "window.ASCII_FRAMES = " + json.dumps(frames, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    out_txt.write_text(frames[len(frames) // 2] + "\n", encoding="utf-8")
    lines = frames[0].splitlines()
    print(f"frames={len(frames)} size={len(lines)}x{len(lines[0])} -> {out_js}")


if __name__ == "__main__":
    main()
